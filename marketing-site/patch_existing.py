"""Build patch.js: the in-browser patch for the existing Pomeroy Agency embeds.

The live pages' HTML is only reachable from a browser on pomeroyagency.com, so
the patch runs there: paPatch(html, slug) returns the page with the TrailBook
header, a TrailBook footer link and, on three pages, the TrailBook promo band.
Every step is idempotent and throws if its anchor is missing, so a page whose
layout changed is reported instead of half-patched.
"""
import json, pathlib
from build import APP, ROOT, part

PROMOS = {
    "home": dict(KICKER="New from Pomeroy Agency &middot; Software",
                 HEADLINE="TrailBook: your books, payroll and sales tax, <em>kept straight</em>.",
                 TEXT="The bookkeeping software we built for owner-run California businesses. Invoices, bank reconciliation, payroll calculation and California sales tax in one place, at one price per business.",
                 LABEL="home_promo"),
    "pricing": dict(KICKER="Software &middot; TrailBook",
                    HEADLINE="Just need the books kept? <em>TrailBook</em>, from $15 a month.",
                    TEXT="Not every business needs a build. TrailBook is our bookkeeping software for California businesses: invoices, reconciliation, payroll prep and sales tax, with every price published.",
                    LABEL="pricing_promo"),
    "systems": dict(KICKER="The books layer &middot; TrailBook",
                    HEADLINE="Your accounting, connected. <em>TrailBook</em> keeps the books.",
                    TEXT="When we connect your systems, the books are part of it. TrailBook is our own bookkeeping software for California businesses, and it works whether or not you hire us for the rest.",
                    LABEL="systems_promo"),
}

def promo(v):
    s = part("promo.html").replace("%%APP%%", APP)
    for k, val in v.items():
        s = s.replace(f"%%{k}%%", val)
    assert "%%" not in s
    return s

header = part("header.html")
footer_li = '<li><a href="https://www.pomeroyagency.com/trailbook" target="_top">TrailBook &middot; Bookkeeping software</a></li>'
js = f"""/* TrailBook patch for the existing Pomeroy Agency embeds. Generated by patch_existing.py. */
(function () {{
var HEADER = {json.dumps(header)};
var PROMO = {json.dumps({k: promo(v) for k, v in PROMOS.items()})};
var FOOTER_LI = {json.dumps(footer_li)};
/* slug -> [promo key, text the promo goes in front of (the section holding it)] */
var PROMO_AT = {{
  "/": ["home", 'id="two-ways"'],
  "/pricing": ["pricing", "Why the Fix is not a report"],
  "/systems-automation": ["systems", "Ready to stop being the integr"]
}};
function need(i, what, slug) {{ if (i < 0) throw new Error(slug + ": anchor not found: " + what); return i; }}
window.paPatch = function (html, slug) {{
  var out = html, i, j;
  /* 1. header: swap the whole <header class="site-header"> block (and a previous V3 style tag) */
  if (out.indexOf("PA-HEADER-V3") < 0) {{
    i = need(out.indexOf('<header class="site-header">'), "header start", slug);
    j = need(out.indexOf("</header>", i), "header end", slug) + "</header>".length;
    var k = out.lastIndexOf("<!-- ══════════ HEADER ══════════ -->", i);
    if (k > -1 && i - k < 80) i = k;
    out = out.slice(0, i) + HEADER + out.slice(j);
  }}
  /* 2. footer: one TrailBook link after Creative & Content in the footer's services list */
  if (out.indexOf(FOOTER_LI) < 0) {{
    var f = need(out.search(/<footer[\\s>]/), "footer", slug);
    var c = need(out.indexOf("creative-content", f), "footer creative-content link", slug);
    var e = need(out.indexOf("</li>", c), "footer li end", slug) + "</li>".length;
    out = out.slice(0, e) + "\\n" + FOOTER_LI + out.slice(e);
  }}
  /* 3. promo band on three pages */
  var at = PROMO_AT[slug];
  if (at && out.indexOf("TRAILBOOK-PROMO START") < 0) {{
    var t = need(out.indexOf(at[1]), "promo anchor " + at[1], slug);
    var s = need(out.lastIndexOf("<section", t), "section before promo anchor", slug);
    out = out.slice(0, s) + PROMO[at[0]] + "\\n" + out.slice(s);
  }}
  return out;
}};
}})();
"""
(ROOT / "dist" / "patch.js").write_text(js)
print(len(js))
